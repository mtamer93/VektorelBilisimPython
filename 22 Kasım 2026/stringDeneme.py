# stringler bir tür özel dizilerdirler. stringler immutable/degistirilemezdir.

sehir = "Kahramanmaraş"

print("Sehir: ", sehir)
print("Sehir[0]: ", sehir[0])
print("Sehir[1]: ", sehir[1])
print("Sehir[-3:]: ", sehir[-3:])

# string metodları ile string üzerinde islemler yapılabilir.
print(sehir.upper())
print(sehir.lower())


