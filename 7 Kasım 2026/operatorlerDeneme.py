# aritmetik operatörler
print(5+9)
print(5*9)
print(20/3)
print(20//3)
print(2**3)
print(20%3)

# string operatorler
print("5" + "9")
print("Vektorel" + "Bilisim")
print("Vektorel " * 4) # * operatorü tekrar eder

# mantıksal operatorler
print(3>8)
print(3!=8)
print(3==8)
print(5>3 or 4<5)
print(5>3 and 4<5)

# ; ile birden çok satırı yan yana yazabiliriz.
print("a") ; print("b")

